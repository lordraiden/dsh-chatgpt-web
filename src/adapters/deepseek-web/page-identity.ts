/**
 * The client identity the DeepSeek Web page attaches to its own API calls — read from the page.
 *
 * ## What the signed-in capture measured
 *
 * Every API request the page makes carries the same non-secret client header family, and a session
 * turn additionally carries the device pair:
 *
 * ```text
 * x-client-bundle-id: com.deepseek.chat     (the app bundle identifier; GB builds use …chat.nov)
 * x-client-platform: web
 * x-client-version: 2.7.0
 * x-client-locale: en_US
 * x-client-timezone-offset: 7200
 * x-device-id: <uuid>                        (the browser's device identity)
 * x-device-model: ""                         (the web app always sends an empty model)
 * x-hif-leim: <device-fingerprint token>     (only when the page has one cached)
 * authorization: Bearer <page token>
 * ```
 *
 * ## Which of these this module invents, and which it reads
 *
 * Nothing here is invented:
 *
 * - the **device id** is read from the same `localStorage` key the app uses
 *   (`deepseek-device-id:chat`), and when the key is absent it is generated with the page's own
 *   `crypto.randomUUID()` and stored there — exactly what the app does on first load;
 * - the **device model** is the empty string the app always writes;
 * - the **HIF leim token** is read from the page's own cache (`hif_leim_cached`, a JSON-serialized
 *   string in the app's storage handle), which its poller fills from `hif.deepseek.com`; an absent
 *   cache means the header is omitted, which is also what the app does (its header builder only adds
 *   the header for a non-empty value);
 * - the **locale** and **timezone offset** are the page's own (`navigator.language`, the browser's
 *   offset in seconds, the same `60 * utcOffset()` the app computes);
 * - the **bundle id** is derived from the page's own `<meta name="region">` with the app's own
 *   mapping (`GB` → `com.deepseek.chat.nov`, otherwise `com.deepseek.chat`);
 * - the **authorization token** is read from the page's own `localStorage["userToken"]` handle, parsed
 *   with the app's own storage shape, at call time — never from configuration and never a constant.
 *
 * The only fixed values are the app's **platform** and **version**, which are build constants of the
 * page rather than values it generates per call (`clientPlatform: "web"`, `appVersion: "2.7.0"` in
 * the bundle's static environment). They are exported here with their provenance; a page whose build
 * moved past them is a bundle-version drift the capture would show, not something this module should
 * guess at.
 *
 * No token, cache value or device id is ever logged: {@link readDeepSeekPageIdentity} returns them for
 * header assembly only.
 */
import type { Page } from "playwright-core";

/** The `localStorage` handle the app persists its API token in (`userTokenStorageHandle`). */
export const DEEPSEEK_WEB_TOKEN_STORAGE_KEY = "userToken";

/** The `localStorage` key of the app's per-scope device identity (`deepseek-device-id:<scope>`). */
export const DEEPSEEK_WEB_DEVICE_ID_STORAGE_KEY = "deepseek-device-id:chat";

/** The `localStorage` key the app's HIF poller caches its leim token in. */
export const DEEPSEEK_WEB_LEIM_STORAGE_KEY = "hif_leim_cached";

/** The app's client platform (`staticEnv.clientPlatform`). */
export const DEEPSEEK_WEB_CLIENT_PLATFORM = "web";

/** The app's client version (`staticEnv.appVersion`). A build constant, pinned by the capture. */
export const DEEPSEEK_WEB_CLIENT_VERSION = "2.7.0";

/** The app bundle identifier the non-GB builds send (`com.deepseek.chat`). */
export const DEEPSEEK_WEB_CLIENT_BUNDLE_ID = "com.deepseek.chat";

/** The app bundle identifier the GB build sends (`com.deepseek.chat.nov`). */
export const DEEPSEEK_WEB_CLIENT_BUNDLE_ID_GB = "com.deepseek.chat.nov";

/** The device model the web app always sends: an empty string (its device module hardcodes it). */
export const DEEPSEEK_WEB_DEVICE_MODEL = "";

/** Everything one page read produced. Secrets live only here, for header assembly. */
export interface DeepSeekPageIdentity {
  /** The full `Authorization` value (`Bearer …`), when the page holds a token. Never logged. */
  readonly authorization?: string;
  /** The browser's device identity, from the app's own storage (or generated by it). */
  readonly deviceId: string;
  /** The page's cached HIF leim token, when its poller has one. */
  readonly leim?: string;
  /** The app's locale key (`en_US`, `zh_CN`, …), from `navigator.language`. */
  readonly locale: string;
  /** The browser's UTC offset in seconds (the app sends `60 * utcOffset()`). */
  readonly timezoneOffsetSeconds: number;
  /** The app bundle identifier, derived from the page's region the way the app derives it. */
  readonly bundleId: string;
}

/**
 * Read the page token out of the app's own storage value.
 *
 * The app's storage handle persists `{"value": <token>, "__version": "0"}`. A value that is not that
 * shape is not a token this build will guess at: an unreadable handle means "no Authorization header",
 * and the provider's own `40002`/`40003` then reports the truth.
 */
export function deepSeekAccessTokenFromStorage(value: string | null | undefined): string | undefined {
  if (typeof value !== "string" || value.trim().length === 0) return undefined;
  let parsed: unknown;
  try {
    parsed = JSON.parse(value) as unknown;
  } catch {
    return undefined;
  }
  if (typeof parsed === "string") return parsed.trim().length === 0 ? undefined : parsed.trim();
  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) return undefined;
  const token = (parsed as Record<string, unknown>)["value"];
  return typeof token === "string" && token.trim().length > 0 ? token.trim() : undefined;
}

/**
 * Read the page's cached HIF leim token.
 *
 * The app's poller keeps it in a JSON-serialized local-storage handle
 * (`createLocalStorageValue({key:"hif_leim_cached", defaultValue:""})`), so the stored text is a JSON
 * string. A raw value is accepted too, because a capture may have been edited by hand; an unreadable
 * value means "no header", the same result as the app's own empty default.
 */
export function deepSeekLeimFromStorage(value: string | null | undefined): string | undefined {
  if (typeof value !== "string") return undefined;
  const trimmed = value.trim();
  if (trimmed.length === 0) return undefined;
  try {
    const parsed = JSON.parse(trimmed) as unknown;
    if (typeof parsed === "string") return parsed.trim().length === 0 ? undefined : parsed.trim();
    if (parsed !== null && typeof parsed === "object") return undefined;
    return undefined;
  } catch {
    return trimmed;
  }
}

/**
 * The app bundle identifier for a region, using the app's own mapping.
 *
 * `HP(brand)` in the bundle maps `deepseek` → `com.deepseek.chat` and `dseek` → `com.deepseek.chat.nov`,
 * and `getBrand()` maps only `GB` to `dseek`. So the region is the page-local input.
 */
export function deepSeekBundleIdForRegion(region: string | undefined): string {
  return region === "GB" ? DEEPSEEK_WEB_CLIENT_BUNDLE_ID_GB : DEEPSEEK_WEB_CLIENT_BUNDLE_ID;
}

/**
 * The non-secret client/device headers, in the captured names.
 *
 * `x-hif-leim` is present only when the page's cache carried a value, exactly like the app's own
 * header builder. `authorization` is not part of this set: it is a credential and is returned only by
 * {@link deepSeekAuthorizationHeader}.
 */
export function deepSeekClientHeaders(identity: DeepSeekPageIdentity): Record<string, string> {
  return {
    "x-client-bundle-id": identity.bundleId,
    "x-client-platform": DEEPSEEK_WEB_CLIENT_PLATFORM,
    "x-client-version": DEEPSEEK_WEB_CLIENT_VERSION,
    "x-client-locale": identity.locale,
    "x-client-timezone-offset": String(identity.timezoneOffsetSeconds),
    "x-device-id": identity.deviceId,
    "x-device-model": DEEPSEEK_WEB_DEVICE_MODEL,
    ...(identity.leim === undefined || identity.leim.length === 0 ? {} : { "x-hif-leim": identity.leim }),
  };
}

/** The `Authorization` header, when the page holds a token. Never a constant, never logged. */
export function deepSeekAuthorizationHeader(identity: DeepSeekPageIdentity): Record<string, string> {
  return identity.authorization === undefined ? {} : { authorization: identity.authorization };
}

/**
 * What the page hands back: the raw handle values, before they are interpreted.
 *
 * Keeping the interpretation in Node means the token never has to be parsed or judged inside the page,
 * and a storage shape this build does not understand simply yields no header.
 */
interface DeepSeekPageIdentityRaw {
  readonly region?: string;
  readonly locale: string;
  readonly timezoneOffsetSeconds: number;
  readonly deviceId: string;
  readonly leimStorage?: string;
  readonly tokenStorage?: string;
}

/**
 * Read the identity from the live page, at call time.
 *
 * Self-contained (Playwright serializes this function): it touches only `document`, `navigator`,
 * `localStorage` and `crypto`, reads no cookie, and writes only the device id the app itself would
 * write when its own key is missing.
 */
function readDeepSeekIdentityInPage(input: {
  readonly deviceKey: string;
  readonly tokenKey: string;
  readonly leimKey: string;
}): DeepSeekPageIdentityRaw {
  const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
  const read = (key: string): string | undefined => {
    try {
      const value = localStorage.getItem(key);
      return value === null ? undefined : value;
    } catch {
      return undefined;
    }
  };

  let deviceId = read(input.deviceKey);
  if (deviceId === undefined || !uuid.test(deviceId)) {
    try {
      deviceId = crypto.randomUUID();
      localStorage.setItem(input.deviceKey, deviceId);
    } catch {
      deviceId = deviceId ?? "";
    }
  }

  const region = document.querySelector('meta[name="region"]')?.getAttribute("content") ?? undefined;
  const language = typeof navigator.language === "string" && navigator.language.length > 0
    ? navigator.language
    : "en-US";
  const leim = read(input.leimKey);
  const tokenStorage = read(input.tokenKey);

  return {
    ...(region === undefined ? {} : { region }),
    locale: language.replace(/-/g, "_"),
    timezoneOffsetSeconds: -new Date().getTimezoneOffset() * 60,
    deviceId: deviceId ?? "",
    ...(leim === undefined ? {} : { leimStorage: leim }),
    ...(tokenStorage === undefined ? {} : { tokenStorage }),
  };
}

/**
 * Read the page's own client identity at call time.
 *
 * @param page - the provider's page (the session's browsing context).
 * @returns the headers' inputs; the `Authorization` value is present only when the page holds a token.
 */
export async function readDeepSeekPageIdentity(page: Page): Promise<DeepSeekPageIdentity> {
  const raw = await page.evaluate(readDeepSeekIdentityInPage, {
    deviceKey: DEEPSEEK_WEB_DEVICE_ID_STORAGE_KEY,
    tokenKey: DEEPSEEK_WEB_TOKEN_STORAGE_KEY,
    leimKey: DEEPSEEK_WEB_LEIM_STORAGE_KEY,
  });
  const token = deepSeekAccessTokenFromStorage(raw.tokenStorage);
  const leim = deepSeekLeimFromStorage(raw.leimStorage);
  return {
    ...(token === undefined ? {} : { authorization: `Bearer ${token}` }),
    deviceId: raw.deviceId,
    ...(leim === undefined ? {} : { leim }),
    locale: raw.locale,
    timezoneOffsetSeconds: raw.timezoneOffsetSeconds,
    bundleId: deepSeekBundleIdForRegion(raw.region),
  };
}
